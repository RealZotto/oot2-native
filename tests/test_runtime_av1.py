"""Contract tests of the AV1 decoder seam over dav1d (runtime/video/av1_dav1d.c, the movie player), and of dav1d's notices.

Builds tests/runtime/av1_test.c with the seam and a dav1d kit (tools/fetch_dav1d.py lays one out; DAV1D_DIR names it), at
-O1 and -O2, and runs each case on the synthetic clips of tests/fixtures/av1 (pictures generated by
tests/fixtures/av1/make_fixtures.py, encoded by rav1e; none is from a game). The pictures are decoded and compared with the
generator's formulas plane by plane at the strides the decoder gives; a damaged unit is refused and the decoder goes on; a
flush starts a new stream.

The decoder tests need a dav1d kit. Without one they skip with the reason said, unless OOT2_REQUIRE_DAV1D is set, as the
Windows continuous-integration job sets it (the job fetches the kit with tools/fetch_dav1d.py first). The notice test needs
nothing.

Run: python -m unittest discover -s tests -v
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import build_game  # noqa: E402

TEST_SOURCE = ROOT / "tests" / "runtime" / "av1_test.c"
END_SOURCE = ROOT / "tests" / "runtime" / "endmark.c"
SEAM = ROOT / "runtime" / "video" / "av1_dav1d.c"
FIXTURES = ROOT / "tests" / "fixtures" / "av1"
LEVELS = ("-O1", "-O2")
CLIPS = (("clip_200x126", 200, 126, 4), ("clip_201x125", 201, 125, 3), ("clip_1920x1080", 1920, 1080, 2))
DAV1D_SHA256 = "686616b7c69eb88d44459391ab25cac13b6647a3b288835c5784e71c1514a5c5"


class Av1Test(unittest.TestCase):
    exes: dict[str, Path] = {}

    @classmethod
    def setUpClass(cls) -> None:
        cc = shutil.which(os.environ.get("OOT2_CC", "clang"))
        if not cc:
            if os.environ.get("OOT2_REQUIRE_CLANG"):
                raise RuntimeError("OOT2_REQUIRE_CLANG is set but no clang was found (OOT2_CC or PATH)")
            raise unittest.SkipTest("no clang on PATH (set OOT2_CC)")
        kit = build_game.find_dav1d()
        if kit is None:
            if os.environ.get("OOT2_REQUIRE_DAV1D"):
                raise RuntimeError("OOT2_REQUIRE_DAV1D is set but DAV1D_DIR holds no dav1d kit (tools/fetch_dav1d.py)")
            raise unittest.SkipTest("no dav1d kit: run tools/fetch_dav1d.py --dest DIR and set DAV1D_DIR to DIR")
        cls.tmp = tempfile.TemporaryDirectory(prefix="oot2-av1-", ignore_cleanup_errors=True)
        out = Path(cls.tmp.name)
        extra = [] if os.name == "nt" else ["-pthread", "-lm"]
        for level in LEVELS:
            exe = out / f"av1_test{level}{'.exe' if os.name == 'nt' else ''}"
            cmd = [cc, "-std=gnu11", level, "-march=x86-64-v3", "-Wall", "-Wextra", "-Werror", "-DOOT2_DAV1D=1",
                   "-I", str(ROOT / "runtime" / "include"), "-I", str(ROOT / "tests" / "runtime"), "-I", str(kit / "include"),
                   str(TEST_SOURCE), str(END_SOURCE), str(SEAM), str(kit / "lib" / "libdav1d.a"), *extra, "-o", str(exe)]
            done = subprocess.run(cmd, capture_output=True, text=True)
            if done.returncode != 0:
                raise RuntimeError(f"build at {level} failed:\n{done.stdout}{done.stderr}")
            cls.exes[level] = exe

    @classmethod
    def tearDownClass(cls) -> None:
        if hasattr(cls, "tmp"):
            cls.tmp.cleanup()

    def run_case(self, level: str, case: str, clip: str, *args: object) -> subprocess.CompletedProcess:
        done = subprocess.run([str(self.exes[level]), case, str(FIXTURES / f"{clip}.ivf"), *map(str, args)],
                              capture_output=True, text=True, timeout=180)
        self.assertEqual(done.returncode, 0, done.stdout + done.stderr)
        self.assertIn(f"ok {case}", done.stdout)
        return done

    def test_planes_and_strides_of_every_clip(self) -> None:
        for level in LEVELS:
            for clip, w, h, frames in CLIPS:
                with self.subTest(level=level, clip=clip):
                    self.run_case(level, "planes", clip, w, h, frames)

    def test_one_picture_per_unit_in_order(self) -> None:
        for level in LEVELS:
            for clip, w, h, frames in CLIPS:
                with self.subTest(level=level, clip=clip):
                    self.run_case(level, "order", clip, w, h, frames)

    def test_a_damaged_unit_is_refused_and_the_decoder_goes_on(self) -> None:
        for level in LEVELS:
            with self.subTest(level=level):
                self.run_case(level, "damaged", "clip_200x126")

    def test_a_flush_starts_a_new_stream(self) -> None:
        for level in LEVELS:
            with self.subTest(level=level):
                self.run_case(level, "flush", "clip_200x126")


class NoticesTest(unittest.TestCase):
    """dav1d is linked into the program, so the notice file lists it with its licence text (the movie player)."""

    def test_dav1d_is_in_the_notices_with_its_licence_text(self) -> None:
        text = (ROOT / "THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8")
        rows = [line for line in text.splitlines() if line.startswith("|") and line.split("|")[1].strip().lower().startswith("dav1d")]
        self.assertTrue(rows, "no row of THIRD_PARTY_NOTICES.md names dav1d")
        row = rows[0]
        self.assertIn("1.5.4", row)
        self.assertIn(DAV1D_SHA256, row)
        self.assertIn("BSD-2-Clause", row)
        for name in re.findall(r"\]\((licenses/[^)]+)\)", row):
            self.assertTrue((ROOT / name).is_file(), f"{name} is named by the dav1d row and is missing")
        licence = (ROOT / "licenses" / "dav1d-BSD-2-Clause.txt").read_text(encoding="utf-8")
        self.assertIn("VideoLAN and dav1d authors", licence)
        self.assertIn("Redistribution and use in source and binary forms", licence)
        self.assertTrue((ROOT / "licenses" / "dav1d-AOM-patent-license.txt").is_file())

    def test_the_fetch_script_refuses_an_archive_with_the_wrong_hash(self) -> None:
        import hashlib

        import fetch_dav1d

        with tempfile.TemporaryDirectory(prefix="oot2-fetch-", ignore_cleanup_errors=True) as tmp:
            src = Path(tmp) / "archive.bin"
            src.write_bytes(b"not a dav1d release")
            dst = Path(tmp) / "got.bin"
            good = hashlib.sha256(b"not a dav1d release").hexdigest()
            fetch_dav1d.download(fetch_dav1d.Archive(src.as_uri(), good), dst)   # the right digest passes
            self.assertEqual(dst.read_bytes(), b"not a dav1d release")
            with self.assertRaises(fetch_dav1d.FetchError):
                fetch_dav1d.download(fetch_dav1d.Archive(src.as_uri(), "0" * 64), Path(tmp) / "bad.bin")
            self.assertFalse((Path(tmp) / "bad.bin").exists(), "a download that failed the check was kept")

    def test_the_nasm_download_is_held_to_its_pinned_digest(self) -> None:
        import io
        from unittest import mock

        import fetch_dav1d

        # whatever the server answers, the Windows path takes it through the pinned digest of NASM_WIN: bytes that are not
        # that release are refused before anything is unpacked or run
        with tempfile.TemporaryDirectory(prefix="oot2-nasm-", ignore_cleanup_errors=True) as tmp:
            with mock.patch.object(fetch_dav1d.urllib.request, "urlopen", lambda url, timeout=0: io.BytesIO(b"not nasm")):
                with self.assertRaises(fetch_dav1d.FetchError) as caught:
                    fetch_dav1d.find_nasm(Path(tmp), True, windows=True)
            self.assertIn(fetch_dav1d.NASM_WIN.url, str(caught.exception))
            self.assertIn("SHA-256", str(caught.exception))
            self.assertFalse((Path(tmp) / "nasm.zip").exists())
            self.assertIsNone(fetch_dav1d.find_nasm(Path(tmp), False, windows=True))   # --no-asm fetches nothing

    def test_a_nasm_archive_that_would_unpack_outside_its_folder_is_refused(self) -> None:
        import hashlib
        import zipfile
        from unittest import mock

        import fetch_dav1d

        with tempfile.TemporaryDirectory(prefix="oot2-nasm-", ignore_cleanup_errors=True) as tmp:
            src = Path(tmp) / "src.zip"
            with zipfile.ZipFile(src, "w") as z:
                z.writestr("../escape.txt", b"x")
            work = Path(tmp) / "work"
            work.mkdir()
            pin = fetch_dav1d.Archive(src.as_uri(), hashlib.sha256(src.read_bytes()).hexdigest())   # the digest is right
            with mock.patch.object(fetch_dav1d, "NASM_WIN", pin):
                with self.assertRaises(fetch_dav1d.FetchError) as caught:
                    fetch_dav1d.find_nasm(work, True, windows=True)
            self.assertIn("would leave the extraction folder", str(caught.exception))
            self.assertFalse((Path(tmp) / "escape.txt").exists())

    def test_the_nasm_pin_is_stated_in_the_notice(self) -> None:
        import fetch_dav1d

        text = (ROOT / "THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8")
        row = next(line for line in text.splitlines() if line.startswith("| dav1d"))
        self.assertIn(fetch_dav1d.NASM_WIN.sha256, row)   # the digest the script holds NASM to is the one the notice states
        self.assertIn(f"NASM {fetch_dav1d.NASM_VERSION}", row)

    def test_the_codec_service_row_names_its_source_and_licence(self) -> None:
        text = (ROOT / "THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8")
        rows = [line for line in text.splitlines() if line.startswith("|") and "runtime/hos/ov_codec.c" in line.split("|")[1]]
        self.assertEqual(len(rows), 1, rows)
        self.assertIn("logic adapted", rows[0].split("|")[1])
        self.assertIn("dm/host/hle_codec_video.c", rows[0])
        self.assertIn("licenses/nxnative-MIT.txt", rows[0])
        self.assertTrue((ROOT / "licenses" / "nxnative-MIT.txt").is_file())
        header = (ROOT / "runtime" / "hos" / "ov_codec.c").read_text(encoding="utf-8").split("#include")[0]
        self.assertIn("adapted logic", header)         # the file says what the notices say
        self.assertNotIn("not copied", header.replace("not a copy of the file", ""))


class WorkflowsTest(unittest.TestCase):
    """The decoder tests must run where the decoder is built: the Windows job requires them, and both jobs hand the kit to
    the tests before they start (the movie player)."""

    @staticmethod
    def workflow(name: str) -> str:
        return (ROOT / ".github" / "workflows" / name).read_text(encoding="utf-8")

    def test_windows_builds_the_kit_and_requires_the_decoder_tests(self) -> None:
        text = self.workflow("windows-build.yml")
        self.assertIn('OOT2_REQUIRE_DAV1D: "1"', text)
        self.assertIn("python tools/fetch_dav1d.py --dest $kit", text)
        self.assertIn('"DAV1D_DIR=$kit" | Out-File -Append -Encoding utf8 $env:GITHUB_ENV', text)
        self.assertLess(text.index("python tools/fetch_dav1d.py"), text.index("python tools/run_tests.py"))

    def test_linux_builds_the_kit_before_the_tests_and_may_skip_the_decoder_tests_with_a_reason(self) -> None:
        text = self.workflow("content-guard.yml")
        self.assertIn('python tools/fetch_dav1d.py --no-asm --dest "$RUNNER_TEMP/dav1d-kit"', text)
        self.assertIn('echo "DAV1D_DIR=$RUNNER_TEMP/dav1d-kit" >> "$GITHUB_ENV"', text)
        self.assertLess(text.index("python tools/fetch_dav1d.py"), text.index("python tools/run_tests.py"))
        self.assertIn("the decoder tests skip with their stated reason", text)   # the Linux job is not a verdict on decoding
        self.assertNotIn("OOT2_REQUIRE_DAV1D", text)

    def test_config_h_has_the_windows_block_and_the_asm_switch(self) -> None:
        import fetch_dav1d

        win = fetch_dav1d.config_h(True, True, True)
        self.assertIn("#define _WIN32_WINNT 0x0601\n", win)
        self.assertIn("#define HAVE_ASM 1\n", win)
        self.assertIn("#define ARCH_X86_64 1\n", win)
        self.assertIn("#define HAVE_ALIGNED_ALLOC 0\n", win)
        self.assertIn("#define HAVE_ASM 0\n", fetch_dav1d.config_h(True, False, True))
        self.assertNotIn("_WIN32_WINNT", fetch_dav1d.config_h(False, True, True))

    def test_the_fetch_script_pins_what_the_notice_says(self) -> None:
        script = (ROOT / "tools" / "fetch_dav1d.py").read_text(encoding="utf-8")
        self.assertIn(DAV1D_SHA256, script)
        self.assertIn('VERSION = "1.5.4"', script)
        notices = (ROOT / "THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8")
        import fetch_dav1d

        self.assertIn(fetch_dav1d.DAV1D.url, notices)   # the archive the script fetches is the one the notice names

    def test_the_assembly_macros_and_the_encoder_of_the_clips_have_their_rows_and_texts(self) -> None:
        text = (ROOT / "THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8")
        rows = {key: [line for line in text.splitlines() if line.startswith("|") and key in line.split("|")[1]]
                for key in ("x86inc.asm", "tests/fixtures/av1/")}
        for key, found in rows.items():
            self.assertEqual(len(found), 1, f"{key}: {found}")
        x86inc, clips = rows["x86inc.asm"][0], rows["tests/fixtures/av1/"][0]
        self.assertIn("ISC", x86inc)
        self.assertIn("licenses/x86inc-ISC.txt", x86inc)
        self.assertIn("Permission to use, copy, modify, and/or distribute", (ROOT / "licenses" / "x86inc-ISC.txt").read_text(encoding="utf-8"))
        self.assertIn("rav1e 0.8.1", clips)
        self.assertIn("BSD-2-Clause", clips)
        encoder = re.search(r"SHA-256 `([0-9a-f]{64})`", clips)
        self.assertIsNotNone(encoder, clips)
        readme = (FIXTURES / "README.md").read_text(encoding="utf-8")
        self.assertIn(encoder[1], readme)   # the encoder is named the same way in the notice and beside the clips
        self.assertIn("rav1e CLIP.y4m", readme)   # and the command that made them is kept next to them


if __name__ == "__main__":
    unittest.main()
